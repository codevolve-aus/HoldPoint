import { jsPDF } from 'jspdf';
import { photoDataURL } from './photos';
import { isoToDMY, rowRuleMessages, specMessage, visible } from './checks';
import type { FormTemplate, Project, Submission } from '../types';

/*
 * Builds the approved PDF in a standard layout: header, job details from the ITP,
 * every section of the form, photos, signatures, and an APPROVED stamp.
 * Phase 2: replace this with the company's Word templates (fill tags, convert to PDF)
 * so the output matches the paper forms exactly.
 */
let fontB64: string | null = null;
export async function loadFont(): Promise<string | null> {
  if (fontB64) return fontB64;
  try {
    const buf = await (await fetch('/fonts/DejaVuSans.ttf')).arrayBuffer();
    let bin = ''; const bytes = new Uint8Array(buf);
    for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
    fontB64 = btoa(bin); return fontB64;
  } catch { return null; }
}

export async function buildPdf(tpl: FormTemplate, sub: Submission, project: Project, approvedBy: string, approvedAt: string): Promise<Blob> {
  const pdf = new jsPDF({ unit: 'mm', format: 'a4' });
  // Values can contain µ, ², ® etc. that the built-in PDF fonts can't show: use DejaVu Sans for values.
  const f64 = await loadFont();
  const VAL = f64 ? 'DejaVu' : 'helvetica';
  if (f64) { pdf.addFileToVFS('DejaVuSans.ttf', f64); pdf.addFont('DejaVuSans.ttf', 'DejaVu', 'normal'); }
  const W = 210, M = 14, CW = W - 2 * M;
  let y = 0;
  let page = 1;

  const header = () => {
    pdf.setDrawColor(0); pdf.setLineWidth(0.6); pdf.line(M, 10, W - M, 10);
    pdf.setFont('helvetica', 'bold'); pdf.setFontSize(10.5);
    const tl = pdf.splitTextToSize(`Document Title: ${tpl.title}`, CW - 58);
    pdf.text(tl.slice(0, 2), M, 15); pdf.text(`Document ID: ${tpl.code}`, M, tl.length > 1 ? 25 : 22);
    // APPROVED stamp
    pdf.setDrawColor(22, 101, 52); pdf.setTextColor(22, 101, 52); pdf.setLineWidth(0.6);
    pdf.roundedRect(W - M - 52, 12, 52, 13, 2, 2);
    pdf.setFontSize(12); pdf.text('APPROVED', W - M - 26, 18, { align: 'center' });
    pdf.setFont(VAL, 'normal'); pdf.setFontSize(6.5); pdf.text(`${approvedBy} · ${approvedAt}`, W - M - 26, 22.5, { align: 'center' });
    pdf.setTextColor(0); pdf.setDrawColor(0); pdf.setLineWidth(0.6); pdf.line(M, 28, W - M, 28);
    y = 34;
  };
  const footer = () => {
    pdf.setLineWidth(0.3); pdf.line(M, 284, W - M, 284);
    pdf.setFontSize(7.5); pdf.setFont('helvetica', 'bold'); pdf.text('Rev Date:', M, 288); pdf.text('Rev:', W - M - 30, 288);
    pdf.setFont('helvetica', 'normal'); pdf.text(tpl.revDate, M + 14, 288); pdf.text(tpl.rev, W - M - 23, 288);
    pdf.text(`Page ${page}`, W / 2, 292, { align: 'center' });
    pdf.text(`${sub.formCode} · ${project.jobNo} · ${isoToDMY(sub.date)} · v${sub.version}`, M, 292);
    pdf.setFontSize(6.5); pdf.setTextColor(120); pdf.text('Generated by HoldPoint · CodeVolve', W - M, 292, { align: 'right' }); pdf.setTextColor(0);
  };
  const need = (h: number) => { if (y + h > 280) { footer(); pdf.addPage(); page++; header(); } };
  const label = (s: string, x: number, yy: number, w: number) => { pdf.setFont('helvetica', 'bold'); pdf.setFontSize(8); pdf.text(pdf.splitTextToSize(s, w), x, yy); };
  const value = (s: string, x: number, yy: number, w: number, bad = false) => {
    pdf.setFont(VAL, 'normal'); pdf.setFontSize(8.5);
    if (bad) pdf.setTextColor(185, 28, 28); else pdf.setTextColor(31, 58, 147);
    const lines = pdf.splitTextToSize(s || '—', w); pdf.text(lines, x, yy); pdf.setTextColor(0);
    return lines.length;
  };
  const sectionTitle = (s: string) => { need(10); pdf.setFillColor(236, 237, 234); pdf.rect(M, y, CW, 6, 'F'); pdf.setFont('helvetica', 'bold'); pdf.setFontSize(9); pdf.text(s, M + 2, y + 4.2); y += 9; };

  const fmt = (f: any, v: any): string => {
    if (v === undefined || v === null || v === '') return '';
    if (Array.isArray(v)) return v.join(', ');
    if (f.type === 'date') return isoToDMY(String(v));
    return `${v}${f.unit && f.type === 'number' && !f.unit.includes(' ') ? ' ' + f.unit : ''}`;
  };

  header();
  // Job details (from the ITP)
  const hd = { ...sub.header, Date: isoToDMY(sub.date) };
  const keys = Object.keys(hd);
  for (let i = 0; i < keys.length; i += 2) {
    need(7);
    [0, 1].forEach((k) => { const key = keys[i + k]; if (!key) return; const x = M + k * (CW / 2); label(key + ':', x, y, 34); value(hd[key as keyof typeof hd] || '', x + 35, y, CW / 2 - 37); });
    y += 6;
  }
  y += 2;

  const photoQueue: { path: string; caption: string }[] = [];
  const drawFields = async (fields: any[], scope: Record<string, any>, all: any) => {
    const vis = fields.filter((f) => visible(f, scope));
    for (const f of vis) {
      const v = scope[f.key];
      if (f.type === 'photo') { if (v) photoQueue.push({ path: v, caption: f.label }); continue; }
      if (f.type === 'signature') {
        need(22); label(f.label, M, y + 4, 60);
        if (v?.image) { try { pdf.addImage(v.image, 'PNG', M + 62, y, 50, 16); } catch { /* ignore */ } pdf.setFontSize(7); pdf.setFont(VAL, 'normal'); pdf.text(`${v.name || ''} · ${v.at || ''}`, M + 62, y + 19); }
        else value('Not signed', M + 62, y + 4, 60);
        y += 22; continue;
      }
      const s = fmt(f, v); const bad = !!specMessage(f, v, scope, all);
      const lines = pdf.splitTextToSize(s || '—', CW - 72).length;
      need(4 + lines * 4);
      label(f.label, M, y, 66); value(s + (bad ? '  (out of spec)' : ''), M + 70, y, CW - 72, bad);
      y += Math.max(5, lines * 4 + 1.5);
    }
  };

  for (const sec of tpl.sections) {
    sectionTitle(sec.title);
    if (sec.repeat) {
      const rows: any[] = sub.values[sec.id] || [];
      for (let i = 0; i < rows.length; i++) {
        need(8); pdf.setFont('helvetica', 'bold'); pdf.setFontSize(8.5); pdf.text(`${sec.repeat.itemLabel} ${i + 1}`, M, y); y += 5;
        await drawFields(sec.fields, rows[i], sub.values);
        rowRuleMessages(sec, rows[i]).forEach((m) => { need(5); value(m, M, y, CW, true); y += 5; });
        y += 1;
      }
    } else {
      await drawFields(sec.fields, sub.values, sub.values);
    }
    y += 2;
  }

  if (photoQueue.length) {
    sectionTitle('Photos');
    let col = 0;
    for (const p of photoQueue) {
      const data = await photoDataURL(p.path);
      if (col === 0) need(62);
      const x = M + col * (CW / 2 + 1);
      if (data) { try { pdf.addImage(data, 'JPEG', x, y, CW / 2 - 2, 52); } catch { /* ignore */ } } else { pdf.rect(x, y, CW / 2 - 2, 52); }
      pdf.setFontSize(7); pdf.setFont(VAL, 'normal'); pdf.text(p.caption, x, y + 56);
      col = (col + 1) % 2; if (col === 0) y += 60;
    }
    if (col === 1) y += 60;
  }

  if (sub.history?.length) {
    sectionTitle('Record');
    for (const h of sub.history) { need(5); pdf.setFont(VAL, 'normal'); pdf.setFontSize(7.5); pdf.text(pdf.splitTextToSize(`${h.at} · ${h.by} · ${h.what}`, CW), M, y); y += 4.5; }
  }
  footer();
  return pdf.output('blob');
}
