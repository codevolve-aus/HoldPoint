import { jsPDF } from 'jspdf';
import { PDFDocument } from 'pdf-lib';
import { getBytes, ref } from 'firebase/storage';
import { storage } from './firebase';
import { isoToDMY } from './db';
import { formFor } from '../forms/registry';
import type { Company, Project, QfRecord } from '../types';

/**
 * A client pack: a cover sheet listing the forms, then each approved form's PDF in ITP line order.
 * The engineer downloads it and emails it to the client; a copy is filed in Submitted Documents.
 */
export async function buildPack(p: Project, recs: QfRecord[], name: string, sentTo: string, note: string, company: Company, by: string, at: string): Promise<Blob> {
  const list = recs.slice().sort((a, b) => a.itemNo - b.itemNo || a.code.localeCompare(b.code) || a.seq - b.seq);

  const cover = new jsPDF({ unit: 'mm', format: 'a4' });
  const M = 18; let y = 22;
  if (company.logo) { try { const ip = cover.getImageProperties(company.logo); const h = 16, w = Math.min(60, ip.width * h / ip.height); cover.addImage(company.logo, M, y - 8, w, h); y += 14; } catch { /* no logo */ } }
  cover.setFont('helvetica', 'bold'); cover.setFontSize(18); cover.text(`QA pack · ${name}`, M, y); y += 9;
  cover.setFont('helvetica', 'normal'); cover.setFontSize(11);
  for (const [k, v] of [['Client', p.client], ['Project', `${p.jobNo} · ${p.name}`], ['Site location', p.location], ['Sent to', sentTo], ['Prepared by', `${by}, ${company.name}`], ['Date', at]]) {
    cover.setFont('helvetica', 'bold'); cover.text(`${k}:`, M, y); cover.setFont('helvetica', 'normal'); cover.text(String(v || '—'), M + 32, y); y += 6.5;
  }
  if (note) { y += 2; const l = cover.splitTextToSize(note, 174); cover.text(l, M, y); y += l.length * 5.5; }
  y += 6;
  cover.setFillColor(191, 191, 191); cover.rect(M, y - 5, 174, 8, 'F'); cover.setFont('helvetica', 'bold'); cover.setFontSize(10);
  const cols = [M + 2, M + 52, M + 72, M + 152];
  ['Form record', 'ITP line', 'Form', 'Day of work'].forEach((h, i) => cover.text(h, cols[i], y)); y += 8;
  cover.setFont('helvetica', 'normal');
  for (const r of list) {
    if (y > 280) { cover.addPage(); y = 20; }
    cover.text(r.ref, cols[0], y); cover.text(String(r.itemNo), cols[1], y);
    cover.text(cover.splitTextToSize(`${r.code} ${formFor(r.code)?.title || ''}`, 78)[0], cols[2], y); cover.text(isoToDMY(r.date), cols[3], y);
    cover.setDrawColor(220); cover.line(M, y + 2.5, M + 174, y + 2.5); y += 8;
  }
  cover.setFontSize(8); cover.setTextColor(90); cover.text(`${list.length} forms, each approved by the engineer. Generated by HoldPoint.`, M, 290);

  const out = await PDFDocument.load(cover.output('arraybuffer'));
  for (const r of list) {
    if (!r.pdfPath) throw new Error(`${r.ref} has no approved PDF yet.`);
    const bytes = await getBytes(ref(storage, r.pdfPath));
    const src = await PDFDocument.load(bytes);
    (await out.copyPages(src, src.getPageIndices())).forEach((pg) => out.addPage(pg));
  }
  return new Blob([(await out.save()) as BlobPart], { type: 'application/pdf' });
}
